fn dispatchXdgSurface(
    context: *anyopaque,
    client: *Server.Client,
    resource: wayring.ObjectHandle,
    message: *wayring.Message,
) !void {
    const xdg_surface: *XdgSurface = @ptrCast(@alignCast(context));
    switch (try generated.xdg_surface_types.decodeRequest(
        &client.connection,
        resource,
        message,
    )) {
        .destroy => if (xdg_surface.role != .none) return client.postError(
            resource,
            @intFromEnum(generated.xdg_surface_types.@"error".defunct_role_object),
            "xdg_surface destroyed before its toplevel",
        ),
        .get_toplevel => |request| {
            if (xdg_surface.role != .none) return client.postError(
                resource,
                @intFromEnum(generated.xdg_surface_types.@"error".already_constructed),
                "xdg_surface already has a role object",
            );
            const toplevel = xdg_surface.allocator.create(Toplevel) catch
                return client.postNoMemory();
            errdefer xdg_surface.allocator.destroy(toplevel);
            xdg_surface.reference() catch return client.postNoMemory();
            errdefer xdg_surface.unreference();
            toplevel.* = .{
                .allocator = xdg_surface.allocator,
                .xdg_surface = xdg_surface,
                .resource = undefined,
                .id = @enumFromInt(xdg_surface.binding.owner.next_toplevel_id),
            };
            xdg_surface.binding.owner.next_toplevel_id = std.math.add(u64, xdg_surface.binding.owner.next_toplevel_id, 1) catch
                return client.postNoMemory();
            xdg_surface.binding.owner.toplevels.append(xdg_surface.allocator, toplevel) catch return client.postNoMemory();
            errdefer _ = xdg_surface.binding.owner.toplevels.pop();
            const version = @min(
                try client.resourceVersion(resource, &generated.xdg_surface),
                generated.xdg_toplevel.version,
            );
            toplevel.resource = client.createResource(
                request.id,
                &generated.xdg_toplevel,
                version,
                .{
                    .context = toplevel,
                    .dispatch = dispatchToplevel,
                    .destroy = destroyToplevel,
                },
            ) catch return client.postNoMemory();
            xdg_surface.role = .{ .toplevel = toplevel };
        },
        .get_popup => |request| try createPopup(xdg_surface, client, resource, request.id, request.parent, request.positioner),
        .set_window_geometry => |request| {
            if (request.width <= 0 or request.height <= 0) return client.postError(
                resource,
                @intFromEnum(generated.xdg_surface_types.@"error".invalid_size),
                "xdg window geometry must have positive dimensions",
            );
            xdg_surface.pending_geometry = .{
                .x = request.x,
                .y = request.y,
                .width = request.width,
                .height = request.height,
            };
        },
        .ack_configure => |request| {
            var index: ?usize = null;
            for (xdg_surface.configures.items, 0..) |configure, i| if (configure.serial == request.serial) {
                index = i;
                break;
            };
            const found = index orelse
                return client.postError(
                    resource,
                    @intFromEnum(generated.xdg_surface_types.@"error".invalid_serial),
                    "unknown xdg configure serial",
                );
            const configure = xdg_surface.configures.items[found];
            xdg_surface.configures.replaceRangeAssumeCapacity(0, found + 1, &.{});
            xdg_surface.last_acked_configure_sequence = configure.sequence;
            if (xdg_surface.role == .popup) {
                const popup = xdg_surface.role.popup;
                popup.pending = configure.popup orelse return client.postError(
                    resource,
                    @intFromEnum(generated.xdg_surface_types.@"error".invalid_serial),
                    "configure does not belong to this xdg_popup",
                );
            }
            xdg_surface.configured = true;
        },
    }
}

fn destroyXdgSurface(
    context: *anyopaque,
    _: *Server.Client,
    _: wayring.ObjectHandle,
) void {
    const xdg_surface: *XdgSurface = @ptrCast(@alignCast(context));
    xdg_surface.resource_alive = false;
    xdg_surface.binding.unreferenceSurface();
    xdg_surface.unreference();
}

fn surfaceDestroyed(context: *anyopaque) void {
    const xdg_surface: *XdgSurface = @ptrCast(@alignCast(context));
    xdg_surface.surface_alive = false;
    if (xdg_surface.role == .toplevel)
        xdg_surface.binding.owner.unpublish(xdg_surface.role.toplevel);
    dismissChildren(xdg_surface.binding.owner, xdg_surface);
    if (xdg_surface.role == .popup) dismissPopup(xdg_surface.role.popup);
    if (!xdg_surface.resource_alive) return;
    xdg_surface.surface.client.postError(
        xdg_surface.resource,
        @intFromEnum(generated.xdg_surface_types.@"error".defunct_role_object),
        "wl_surface destroyed before its xdg_surface",
    ) catch {};
}

fn dispatchToplevel(
    context: *anyopaque,
    client: *Server.Client,
    resource: wayring.ObjectHandle,
    message: *wayring.Message,
) !void {
    const toplevel: *Toplevel = @ptrCast(@alignCast(context));
    switch (try generated.xdg_toplevel_types.decodeRequest(
        &client.connection,
        resource,
        message,
    )) {
        .destroy => {},
        .set_title => |request| try replaceText(
            toplevel,
            &toplevel.title,
            request.title,
            .title,
            client,
        ),
        .set_app_id => |request| try replaceText(
            toplevel,
            &toplevel.app_id,
            request.app_id,
            .app_id,
            client,
        ),
        .set_max_size => |request| {
            if (request.width < 0 or request.height < 0) return client.postError(
                resource,
                @intFromEnum(generated.xdg_toplevel_types.@"error".invalid_size),
                "negative maximum toplevel size",
            );
            toplevel.maximum_width = request.width;
            toplevel.maximum_height = request.height;
        },
        .set_min_size => |request| {
            if (request.width < 0 or request.height < 0) return client.postError(
                resource,
                @intFromEnum(generated.xdg_toplevel_types.@"error".invalid_size),
                "negative minimum toplevel size",
            );
            toplevel.minimum_width = request.width;
            toplevel.minimum_height = request.height;
        },
        .set_parent,
        .show_window_menu,
        .move,
        .resize,
        .set_maximized,
        .unset_maximized,
        .set_fullscreen,
        .unset_fullscreen,
        .set_minimized,
        => {},
    }
}

fn replaceText(
    toplevel: *Toplevel,
    destination: *?[]u8,
    source: []const u8,
    field: ToplevelMetadataField,
    client: *Server.Client,
) !void {
    const copy = toplevel.allocator.dupe(u8, source) catch return client.postNoMemory();
    if (destination.*) |previous| toplevel.allocator.free(previous);
    destination.* = copy;
    if (toplevel.xdg_surface.binding.owner.toplevel_observer) |observer|
        observer.metadata_changed(observer.context, toplevel.id, field);
}

fn destroyToplevel(
    context: *anyopaque,
    _: *Server.Client,
    _: wayring.ObjectHandle,
) void {
    const toplevel: *Toplevel = @ptrCast(@alignCast(context));
    const shell = toplevel.xdg_surface.binding.owner;
    dismissChildren(shell, toplevel.xdg_surface);
    if (toplevel.xdg_surface.role == .toplevel and toplevel.xdg_surface.role.toplevel == toplevel) {
        toplevel.xdg_surface.role = .none;
        toplevel.xdg_surface.mapped = false;
        resetConfigureState(toplevel.xdg_surface, null);
        if (shell.tree.find(toplevel.xdg_surface.surface)) |node| shell.tree.deactivateNow(node);
    }
    toplevel.deinit();
}

fn sendInitialConfigure(xdg_surface: *XdgSurface) !void {
    const client = xdg_surface.surface.client;
    switch (xdg_surface.role) {
        .toplevel => try sendToplevelConfigure(xdg_surface, true),
        .popup => |popup| {
            if (!parentMapped(popup)) return invalidPopupParent(xdg_surface, "xdg_popup parent is not mapped");
            sendPopupConfigure(popup, popup.rules, null) catch |err| switch (err) {
                error.InvalidParent => return invalidPopupParent(xdg_surface, "invalid xdg_popup parent geometry"),
                error.InvalidPositioner => return invalidPopupPositioner(xdg_surface, "xdg_positioner anchor rectangle is outside its parent"),
                error.OutOfMemory => return client.postNoMemory(),
                else => return err,
            };
        },
        .none => unreachable,
    }
}

fn sendToplevelConfigure(xdg_surface: *XdgSurface, initial: bool) !void {
    const toplevel = switch (xdg_surface.role) {
        .toplevel => |value| value,
        .none, .popup => unreachable,
    };
    const client = xdg_surface.surface.client;
    if (!xdg_surface.resource_alive or client.state != .active) return;
    xdg_surface.configures.ensureUnusedCapacity(xdg_surface.allocator, 1) catch
        return client.postNoMemory();
    if (initial) {
        const version = try client.resourceVersion(toplevel.resource, &generated.xdg_toplevel);
        if (version >= 5) generated.xdg_toplevel_types.events.wm_capabilities(
            &client.connection,
            toplevel.resource,
            &.{},
        ) catch return client.postNoMemory();
    }
    if (toplevel.decoration_handler) |handler| {
        generated.zxdg_toplevel_decoration_v1_types.events.configure(
            &client.connection,
            handler.resource,
            @intFromEnum(
                generated.zxdg_toplevel_decoration_v1_types.mode.client_side,
            ),
        ) catch return client.postNoMemory();
        toplevel.decoration_configure_sent = true;
    }
    if (xdg_surface.binding.owner.toplevel_configure_handler) |handler|
        try handler.configure(handler.context, xdg_surface.surface);
    const activated_state = [_]u32{@intFromEnum(
        generated.xdg_toplevel_types.state.activated,
    )};
    const states: []const u8 = if (toplevel.activated)
        std.mem.sliceAsBytes(activated_state[0..])
    else
        &.{};
    generated.xdg_toplevel_types.events.configure(
        &client.connection,
        toplevel.resource,
        0,
        0,
        states,
    ) catch return client.postNoMemory();
    const serial = xdg_surface.surface.owner.server.nextSerial();
    generated.xdg_surface_types.events.configure(
        &client.connection,
        xdg_surface.resource,
        serial,
    ) catch return client.postNoMemory();
    xdg_surface.configures.appendAssumeCapacity(.{
        .serial = serial,
        .sequence = xdg_surface.next_configure_sequence,
    });
    xdg_surface.next_configure_sequence += 1;
    if (initial) xdg_surface.initial_configure_sent = true;
}

