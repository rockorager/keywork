const Binding = struct {
    allocator: std.mem.Allocator,
    owner: *XdgShell,
    resource: wayring.ObjectHandle,
    references: usize = 1,
    surface_count: usize = 0,

    fn reference(self: *Binding) !void {
        if (self.references == std.math.maxInt(usize)) return error.ReferenceOverflow;
        self.references += 1;
        self.surface_count += 1;
    }

    fn unreferenceSurface(self: *Binding) void {
        std.debug.assert(self.surface_count > 0);
        self.surface_count -= 1;
        self.unreference();
    }

    fn unreference(self: *Binding) void {
        std.debug.assert(self.references > 0);
        self.references -= 1;
        if (self.references != 0) return;
        self.allocator.destroy(self);
    }
};

const XdgSurface = struct {
    allocator: std.mem.Allocator,
    binding: *Binding,
    surface: *CompositorGlobal.Surface,
    resource: wayring.ObjectHandle,
    references: usize = 1,
    resource_alive: bool = true,
    surface_alive: bool = true,
    role: union(enum) { none, toplevel: *Toplevel, popup: *Popup } = .none,
    configures: std.ArrayList(Configure) = .empty,
    // Commit capture records this local ordering boundary so an older queued
    // unmap cannot invalidate a configure generated by a later request.
    next_configure_sequence: u64 = 0,
    last_acked_configure_sequence: ?u64 = null,
    initial_configure_sent: bool = false,
    configured: bool = false,
    pending_geometry: ?Geometry = null,
    current_geometry: ?Geometry = null,
    mapped: bool = false,

    fn reference(self: *XdgSurface) !void {
        if (self.references == std.math.maxInt(usize)) return error.ReferenceOverflow;
        self.references += 1;
    }

    fn unreference(self: *XdgSurface) void {
        std.debug.assert(self.references > 0);
        self.references -= 1;
        if (self.references != 0) return;
        if (self.surface.role_context == @as(*anyopaque, @ptrCast(self))) {
            self.surface.clearRoleCommitHandler(self);
            self.surface.clearRole(self);
        }
        self.surface.unreference();
        self.configures.deinit(self.allocator);
        self.allocator.destroy(self);
    }
};

const Toplevel = struct {
    allocator: std.mem.Allocator,
    xdg_surface: *XdgSurface,
    resource: wayring.ObjectHandle,
    id: ToplevelId,
    published: bool = false,
    activated: bool = false,
    activation_pending: bool = false,
    title: ?[]u8 = null,
    app_id: ?[]u8 = null,
    tag: ?[]u8 = null,
    description: ?[]u8 = null,
    icon: ?ToplevelIcon = null,
    pending_icon: ?ToplevelIcon = null,
    pending_icon_changed: bool = false,
    dialog_handler: ?ToplevelDialogHandler = null,
    modal: bool = false,
    decoration_handler: ?ToplevelDecorationHandler = null,
    decoration_preference: DecorationPreference = .only_csd,
    decoration_configure_sent: bool = false,
    minimum_width: i32 = 0,
    minimum_height: i32 = 0,
    maximum_width: i32 = 0,
    maximum_height: i32 = 0,

    fn deinit(self: *Toplevel) void {
        const owner = self.xdg_surface.binding.owner;
        owner.unpublish(self);
        const index = std.mem.indexOfScalar(*Toplevel, owner.toplevels.items, self) orelse unreachable;
        _ = owner.toplevels.swapRemove(index);
        if (self.title) |title| self.allocator.free(title);
        if (self.app_id) |app_id| self.allocator.free(app_id);
        if (self.tag) |tag| self.allocator.free(tag);
        if (self.description) |description| self.allocator.free(description);
        if (self.icon) |*icon| icon.deinit(self.allocator);
        if (self.pending_icon) |*icon| icon.deinit(self.allocator);
        if (self.dialog_handler) |handler| {
            self.dialog_handler = null;
            self.modal = false;
            handler.toplevel_destroyed(handler.context);
        }
        if (self.decoration_handler) |handler| {
            self.decoration_handler = null;
            self.decoration_preference = .only_csd;
            self.decoration_configure_sent = false;
            handler.toplevel_destroyed(handler.context);
        }
        self.xdg_surface.unreference();
        self.allocator.destroy(self);
    }
};

