fn toplevelHasBuffer(toplevel: *const Toplevel) bool {
    if (toplevel.xdg_surface.mapped or
        toplevel.xdg_surface.surface.current_buffer_format != null)
    {
        return true;
    }
    return switch (toplevel.xdg_surface.surface.pending_attachment) {
        .buffer => true,
        .unchanged, .removed => false,
    };
}

fn toplevelFor(
    self: *XdgShell,
    client: *const Server.Client,
    handle: wayring.ObjectHandle,
) !*Toplevel {
    const toplevel: *Toplevel = @ptrCast(@alignCast(
        try client.resourceContext(handle, &generated.xdg_toplevel),
    ));
    if (toplevel.xdg_surface.binding.owner != self) return error.WrongToplevel;
    return toplevel;
}

/// Applies xdg-shell's configure barrier to one atomic surface commit. This
/// is called after request dispatch and before any buffer I/O is submitted.
pub fn handleCommit(self: *XdgShell, commit: *CompositorGlobal.Commit) !CommitResult {
    if (commit.surface.role_owner != @as(*const anyopaque, @ptrCast(self))) {
        const node = try self.tree.nodeFor(commit.surface);
        if (node.parent != null) return .{};
        const active = switch (commit.attachment) {
            .buffer => true,
            .removed => false,
            .unchanged => node.current_active,
        };
        return .{ .direct_update = try self.tree.captureDirect(node, .{}, active) };
    }
    const context = commit.surface.role_context orelse return .{};
    const xdg_surface: *XdgSurface = @ptrCast(@alignCast(context));
    if (!xdg_surface.resource_alive) return .{};
    if (xdg_surface.role == .none) {
        try xdg_surface.surface.client.postError(
            xdg_surface.resource,
            @intFromEnum(generated.xdg_surface_types.@"error".not_constructed),
            "xdg_surface has no role object",
        );
        return .{};
    }
    const role_state = commit.takeRoleState(self);
    defer if (role_state) |state| state.deinit(state.context);
    const toplevel_commit_state: ?*ToplevelCommitState = if (role_state) |state| switch (xdg_surface.role) {
        .toplevel => |toplevel| state: {
            const captured: *ToplevelCommitState = @ptrCast(@alignCast(state.context));
            break :state if (std.meta.eql(captured.toplevel, toplevel.resource))
                captured
            else
                null;
        },
        .none, .popup => null,
    } else null;
    if (xdg_surface.pending_geometry) |geometry| {
        xdg_surface.current_geometry = geometry;
        xdg_surface.pending_geometry = null;
    }
    if (xdg_surface.role == .toplevel and commit.attachment == .buffer) {
        const toplevel = xdg_surface.role.toplevel;
        if (toplevel.decoration_handler) |handler| {
            if (handler.version == 1 and !toplevel.decoration_configure_sent) {
                try xdg_surface.surface.client.postError(
                    handler.resource,
                    @intFromEnum(
                        generated.zxdg_toplevel_decoration_v1_types.@"error".unconfigured_buffer,
                    ),
                    "buffer committed before the initial decoration configure",
                );
                return .{};
            }
        }
    }
    if (!xdg_surface.initial_configure_sent) {
        if (commit.attachment == .buffer) {
            try xdg_surface.surface.client.postError(
                xdg_surface.resource,
                @intFromEnum(generated.xdg_surface_types.@"error".unconfigured_buffer),
                "buffer committed before initial xdg configure",
            );
            return .{};
        }
        if (xdg_surface.role == .popup and !parentMapped(xdg_surface.role.popup)) {
            try invalidPopupParent(xdg_surface, "xdg_popup parent is not mapped");
            return .{};
        }
        if (xdg_surface.role == .toplevel and toplevel_commit_state != null)
            applyToplevelIcon(toplevel_commit_state.?, xdg_surface.role.toplevel);
        try sendInitialConfigure(xdg_surface);
        return .{ .disposition = .configure_only };
    }
    if (commit.attachment == .buffer and !xdg_surface.configured) {
        try xdg_surface.surface.client.postError(
            xdg_surface.resource,
            @intFromEnum(generated.xdg_surface_types.@"error".unconfigured_buffer),
            "buffer committed before acknowledging xdg configure",
        );
        return .{};
    }
    if (xdg_surface.role == .toplevel and toplevel_commit_state != null)
        applyToplevelIcon(toplevel_commit_state.?, xdg_surface.role.toplevel);
    const node = try self.tree.nodeFor(commit.surface);
    var position: SurfaceTree.Position = .{};
    switch (xdg_surface.role) {
        .toplevel => switch (commit.attachment) {
            .buffer => xdg_surface.mapped = true,
            .removed => {
                dismissChildren(self, xdg_surface);
                xdg_surface.mapped = false;
                resetConfigureState(
                    xdg_surface,
                    if (toplevel_commit_state) |captured|
                        captured.configure_reset_boundary
                    else
                        null,
                );
            },
            .unchanged => {},
        },
        .popup => |popup| {
            if (popup.dismissed) {
                xdg_surface.mapped = false;
                popup.mapped = false;
            } else switch (commit.attachment) {
                .buffer => {
                    if (!parentMapped(popup)) {
                        try invalidPopupParent(xdg_surface, "xdg_popup parent is not mapped");
                        return .{};
                    }
                    if (popup.pending) |pending| {
                        popup.current = pending;
                        popup.rules = pending.rules;
                        popup.pending = null;
                    }
                    if (popup.current == null) return clientProtocolError(
                        xdg_surface,
                        generated.xdg_surface_types.@"error".unconfigured_buffer,
                        "popup buffer committed without an acknowledged configure",
                    );
                    popup.mapped = true;
                    xdg_surface.mapped = true;
                },
                .removed => {
                    dismissChildren(self, xdg_surface);
                    popup.mapped = false;
                    popup.dismissed = false;
                    popup.pending = null;
                    popup.current = null;
                    xdg_surface.mapped = false;
                    resetConfigureState(xdg_surface, null);
                },
                .unchanged => if (popup.pending) |pending| {
                    popup.current = pending;
                    popup.rules = pending.rules;
                    popup.pending = null;
                },
            }
            position = popupTreePosition(popup);
        },
        .none => unreachable,
    }
    return .{ .direct_update = try self.tree.captureDirect(
        node,
        position,
        xdg_surface.mapped,
    ) };
}

/// Keeps retained hierarchy visibility consistent when a staged SHM copy
/// cannot produce the buffer that an xdg commit attempted to map.
pub fn deactivateFailedBuffer(self: *XdgShell, surface: *CompositorGlobal.Surface) void {
    if (surface.role_owner != @as(*const anyopaque, @ptrCast(self))) return;
    const context = surface.role_context orelse return;
    const xdg_surface: *XdgSurface = @ptrCast(@alignCast(context));
    xdg_surface.mapped = false;
    if (xdg_surface.role == .popup) xdg_surface.role.popup.mapped = false;
}

fn clientProtocolError(
    xdg_surface: *XdgSurface,
    code: generated.xdg_surface_types.@"error",
    text: []const u8,
) !CommitResult {
    try xdg_surface.surface.client.postError(xdg_surface.resource, @intFromEnum(code), text);
    return .{};
}

fn resetConfigureState(xdg_surface: *XdgSurface, boundary: ?u64) void {
    var retained_after_boundary = false;
    var acknowledged_after_boundary = false;
    if (boundary) |sequence| {
        // Only state predating the unmap request is stale. Configures sent or
        // acknowledged after that request configure the next mapping.
        var stale_count: usize = 0;
        while (stale_count < xdg_surface.configures.items.len and
            xdg_surface.configures.items[stale_count].sequence < sequence)
        {
            stale_count += 1;
        }
        xdg_surface.configures.replaceRangeAssumeCapacity(0, stale_count, &.{});
        retained_after_boundary = xdg_surface.configures.items.len != 0;
        acknowledged_after_boundary = if (xdg_surface.last_acked_configure_sequence) |acknowledged|
            acknowledged >= sequence
        else
            false;
        if (!acknowledged_after_boundary)
            xdg_surface.last_acked_configure_sequence = null;
    } else {
        xdg_surface.configures.clearRetainingCapacity();
        xdg_surface.last_acked_configure_sequence = null;
    }
    xdg_surface.initial_configure_sent = retained_after_boundary or
        acknowledged_after_boundary;
    xdg_surface.configured = acknowledged_after_boundary;
    if (xdg_surface.role == .toplevel) {
        const toplevel = xdg_surface.role.toplevel;
        toplevel.decoration_configure_sent =
            toplevel.decoration_handler != null and xdg_surface.initial_configure_sent;
    }
}

fn applyToplevelIcon(
    captured: *ToplevelCommitState,
    toplevel: *Toplevel,
) void {
    if (!captured.icon_changed) return;
    if (toplevel.icon) |*icon| icon.deinit(toplevel.allocator);
    toplevel.icon = captured.icon;
    captured.icon = null;
}

fn captureRoleCommitState(
    context: *anyopaque,
) error{OutOfMemory}!?CompositorGlobal.RoleCommitState {
    const xdg_surface: *XdgSurface = @ptrCast(@alignCast(context));
    const toplevel = switch (xdg_surface.role) {
        .toplevel => |value| value,
        .none, .popup => return null,
    };
    const configure_reset_boundary: ?u64 = switch (xdg_surface.surface.pending_attachment) {
        .removed => xdg_surface.next_configure_sequence,
        .unchanged, .buffer => null,
    };
    if (!toplevel.pending_icon_changed and configure_reset_boundary == null) return null;
    const captured = toplevel.allocator.create(ToplevelCommitState) catch
        return error.OutOfMemory;
    captured.* = .{
        .allocator = toplevel.allocator,
        .toplevel = toplevel.resource,
        .icon_changed = toplevel.pending_icon_changed,
        .icon = toplevel.pending_icon,
        .configure_reset_boundary = configure_reset_boundary,
    };
    toplevel.pending_icon = null;
    toplevel.pending_icon_changed = false;
    return .{
        .owner = xdg_surface.binding.owner,
        .context = captured,
        .deinit = ToplevelCommitState.deinit,
    };
}

fn popupTreePosition(popup: *const Popup) SurfaceTree.Position {
    const placement = (popup.current orelse return .{}).placement.position;
    const parent_geometry = popup.parent.current_geometry orelse Geometry{
        .x = 0,
        .y = 0,
        .width = 1,
        .height = 1,
    };
    const popup_geometry = popup.xdg_surface.current_geometry orelse Geometry{
        .x = 0,
        .y = 0,
        .width = 1,
        .height = 1,
    };
    return .{
        .x = parent_geometry.x +| placement.x -| popup_geometry.x,
        .y = parent_geometry.y +| placement.y -| popup_geometry.y,
    };
}

fn bind(context: *anyopaque, client: *Server.Client, id: u32, version: u32) !void {
    const self: *XdgShell = @ptrCast(@alignCast(context));
    const binding = self.allocator.create(Binding) catch return client.postNoMemory();
    errdefer self.allocator.destroy(binding);
    binding.* = .{
        .allocator = self.allocator,
        .owner = self,
        .resource = undefined,
    };
    binding.resource = client.createResource(id, &generated.xdg_wm_base, version, .{
        .context = binding,
        .dispatch = dispatchWmBase,
        .destroy = destroyBinding,
    }) catch return client.postNoMemory();
}

fn dispatchWmBase(
    context: *anyopaque,
    client: *Server.Client,
    resource: wayring.ObjectHandle,
    message: *wayring.Message,
) !void {
    const binding: *Binding = @ptrCast(@alignCast(context));
    switch (try generated.xdg_wm_base_types.decodeRequest(
        &client.connection,
        resource,
        message,
    )) {
        .destroy => if (binding.surface_count != 0) return client.postError(
            resource,
            @intFromEnum(generated.xdg_wm_base_types.@"error".defunct_surfaces),
            "xdg_wm_base destroyed before its surfaces",
        ),
        .create_positioner => |request| {
            const positioner = binding.allocator.create(Positioner) catch
                return client.postNoMemory();
            errdefer binding.allocator.destroy(positioner);
            positioner.* = .{ .allocator = binding.allocator };
            const version = @min(
                try client.resourceVersion(resource, &generated.xdg_wm_base),
                generated.xdg_positioner.version,
            );
            _ = client.createResource(request.id, &generated.xdg_positioner, version, .{
                .context = positioner,
                .dispatch = dispatchPositioner,
                .destroy = destroyPositioner,
            }) catch return client.postNoMemory();
        },
        .get_xdg_surface => |request| {
            const object = client.connection.object(request.surface) orelse
                return error.UnknownSurface;
            const surface_handle: wayring.ObjectHandle = .{
                .id = request.surface,
                .generation = object.generation,
            };
            const surface = try CompositorGlobal.surfaceFor(client, surface_handle);
            const xdg_surface = binding.allocator.create(XdgSurface) catch
                return client.postNoMemory();
            errdefer binding.allocator.destroy(xdg_surface);
            xdg_surface.* = .{
                .allocator = binding.allocator,
                .binding = binding,
                .surface = surface,
                .resource = undefined,
            };
            surface.reference() catch return client.postNoMemory();
            errdefer surface.unreference();
            surface.setRole(binding.owner, xdg_surface, surfaceDestroyed) catch return client.postError(
                resource,
                @intFromEnum(generated.xdg_wm_base_types.@"error".role),
                "wl_surface already has a role",
            );
            errdefer surface.clearRole(xdg_surface);
            surface.setRoleCommitHandler(.{
                .context = xdg_surface,
                .capture = captureRoleCommitState,
            });
            errdefer surface.clearRoleCommitHandler(xdg_surface);
            binding.reference() catch return client.postNoMemory();
            errdefer binding.unreferenceSurface();
            const version = @min(
                try client.resourceVersion(resource, &generated.xdg_wm_base),
                generated.xdg_surface.version,
            );
            xdg_surface.resource = client.createResource(
                request.id,
                &generated.xdg_surface,
                version,
                .{
                    .context = xdg_surface,
                    .dispatch = dispatchXdgSurface,
                    .destroy = destroyXdgSurface,
                },
            ) catch return client.postNoMemory();
        },
        .pong => {},
    }
}

fn destroyBinding(
    context: *anyopaque,
    _: *Server.Client,
    _: wayring.ObjectHandle,
) void {
    const binding: *Binding = @ptrCast(@alignCast(context));
    binding.unreference();
}

fn dispatchPositioner(
    context: *anyopaque,
    client: *Server.Client,
    resource: wayring.ObjectHandle,
    message: *wayring.Message,
) !void {
    const positioner: *Positioner = @ptrCast(@alignCast(context));
    switch (try generated.xdg_positioner_types.decodeRequest(
        &client.connection,
        resource,
        message,
    )) {
        .destroy => {},
        .set_size => |request| {
            if (request.width <= 0 or request.height <= 0) return invalidPositioner(client, resource, "positioner size must be positive");
            positioner.rules.size = .{ .width = request.width, .height = request.height };
        },
        .set_anchor_rect => |request| {
            if (request.width < 0 or request.height < 0) return invalidPositioner(client, resource, "anchor rectangle size must not be negative");
            positioner.rules.anchor_rect = .{ .x = request.x, .y = request.y, .width = request.width, .height = request.height };
        },
        .set_anchor => |request| {
            const value = request.anchor;
            if (value > 8) return invalidPositioner(client, resource, "invalid anchor");
            positioner.rules.anchor = @enumFromInt(value);
        },
        .set_gravity => |request| {
            const value = request.gravity;
            if (value > 8) return invalidPositioner(client, resource, "invalid gravity");
            positioner.rules.gravity = @enumFromInt(value);
        },
        .set_constraint_adjustment => |request| {
            const value: u32 = @bitCast(request.constraint_adjustment);
            if (value & ~@as(u32, 0x3f) != 0) return invalidPositioner(client, resource, "invalid constraint adjustment");
            positioner.rules.adjustment = @bitCast(value);
        },
        .set_offset => |request| positioner.rules.offset = .{ .x = request.x, .y = request.y },
        .set_reactive => positioner.rules.reactive = true,
        .set_parent_size => |request| {
            if (request.parent_width <= 0 or request.parent_height <= 0) return invalidPositioner(client, resource, "parent size must be positive");
            positioner.rules.parent_size = .{ .width = request.parent_width, .height = request.parent_height };
        },
        .set_parent_configure => |request| positioner.rules.parent_configure = request.serial,
    }
}

